import XCTest
@testable import Hermes

final class CantripGzipTests: XCTestCase {
    private let body = Data(String(repeating: #"{"text":"compressible \#u{2726}"},"#, count: 200).utf8)
    /// Python's gzip.compress(body, mtime=0).
    private let plain = Data([0x1F, 0x8B, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0xFF, 0xED, 0xC9, 0xB1, 0x0D, 0x40, 0x40, 0x14, 0x00, 0xD0, 0x55, 0xE4, 0xD7, 0x26, 0x30, 0x0E, 0xF9, 0x85, 0x84, 0x10, 0x77, 0x85, 0xE4, 0x62, 0x13, 0xB5, 0xC1, 0x4C, 0x62, 0x0D, 0xC5, 0x7B, 0xED, 0x6B, 0x51, 0xF3, 0xAC, 0x31, 0xC4, 0xB4, 0xAD, 0xFB, 0x91, 0xA5, 0xCC, 0xE3, 0x92, 0xDD, 0x7B, 0x3F, 0x71, 0xF5, 0xCD, 0x39, 0xE7, 0x9C, 0x73, 0xCE, 0x39, 0xE7, 0x9C, 0x73, 0xCE, 0x39, 0xE7, 0xDC, 0x6F, 0xEF, 0x03, 0x9B, 0x1C, 0x7E, 0xEB, 0xE0, 0x15, 0x00, 0x00])
    /// The same body with a stored file name (the FNAME header field).
    private let named = Data([0x1F, 0x8B, 0x08, 0x08, 0x00, 0x00, 0x00, 0x00, 0x02, 0xFF, 0x6E, 0x61, 0x6D, 0x65, 0x64, 0x2E, 0x6A, 0x73, 0x6F, 0x6E, 0x00, 0xED, 0xC9, 0xB1, 0x0D, 0x40, 0x40, 0x14, 0x00, 0xD0, 0x55, 0xE4, 0xD7, 0x26, 0x30, 0x0E, 0xF9, 0x85, 0x84, 0x10, 0x77, 0x85, 0xE4, 0x62, 0x13, 0xB5, 0xC1, 0x4C, 0x62, 0x0D, 0xC5, 0x7B, 0xED, 0x6B, 0x51, 0xF3, 0xAC, 0x31, 0xC4, 0xB4, 0xAD, 0xFB, 0x91, 0xA5, 0xCC, 0xE3, 0x92, 0xDD, 0x7B, 0x3F, 0x71, 0xF5, 0xCD, 0x39, 0xE7, 0x9C, 0x73, 0xCE, 0x39, 0xE7, 0x9C, 0x73, 0xCE, 0x39, 0xE7, 0xDC, 0x6F, 0xEF, 0x03, 0x9B, 0x1C, 0x7E, 0xEB, 0xE0, 0x15, 0x00, 0x00])

    func testDecodesGzipWithAndWithoutHeaderFields() {
        XCTAssertEqual(CantripGzip.decode(plain, limit: 1 << 20), body)
        XCTAssertEqual(CantripGzip.decode(named, limit: 1 << 20), body)
    }

    func testRejectsCorruptTruncatedOversizedOrForeignBodies() {
        var corrupt = plain
        corrupt[corrupt.count / 2] ^= 0xFF
        XCTAssertNil(CantripGzip.decode(corrupt, limit: 1 << 20))
        XCTAssertNil(CantripGzip.decode(plain.prefix(plain.count - 3), limit: 1 << 20))
        XCTAssertNil(CantripGzip.decode(plain, limit: 100))
        XCTAssertNil(CantripGzip.decode(Data("not gzip at all, really".utf8), limit: 1 << 20))
    }

    func testBodyFollowsContentEncoding() {
        XCTAssertEqual(CantripGzip.body(body, contentEncoding: nil, limit: 1 << 20), body)
        XCTAssertEqual(CantripGzip.body(body, contentEncoding: "identity", limit: 1 << 20), body)
        XCTAssertEqual(CantripGzip.body(plain, contentEncoding: "GZIP", limit: 1 << 20), body)
        XCTAssertNil(CantripGzip.body(plain, contentEncoding: "br", limit: 1 << 20),
                     "An encoding the client never asks for is an invalid response")
    }

    func testCRC32MatchesTheStandardCheckValue() {
        XCTAssertEqual(CantripGzip.crc32(Data("123456789".utf8)), 0xCBF4_3926)
    }
}
